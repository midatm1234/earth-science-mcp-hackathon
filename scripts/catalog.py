"""Browse and maintain the hackathon catalog of MCP servers and agent skills.

    uv run python scripts/catalog.py search temperature bias   # find existing capabilities
    uv run python scripts/catalog.py show obs-model-starter     # print one entry
    uv run python scripts/catalog.py index                      # regenerate catalog/index.md
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]


def load(root: Path) -> list[dict]:
    out = []
    for path in sorted((root / "catalog" / "entries").glob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        data["_file"] = path.relative_to(root).as_posix()
        out.append(data)
    return out


def _cell(value) -> str:
    text = " ".join(str(value).split())
    return text.replace("|", "\\|")


def render_index(root: Path = REPO) -> str:
    entries = load(root)
    lines = [
        "# Catalog index",
        "",
        "Generated by `uv run python scripts/catalog.py index` from [entries/](entries/). Do not edit by hand.",
        "",
        "Status columns are independent: **review** is the organizers' decision, **local** is the author's",
        "verification, **peer** is independent cross-team testing, **hosting** is whether a service is running.",
        "A merged or accepted entry does not mean a service is running.",
        "",
        "| Id | Type | Origin | Purpose | Credentials | Review | Local | Peer | Hosting |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        st = e.get("status") or {}
        peers = st.get("peer_testing") or []
        peer = ", ".join(p.get("result", "?") for p in peers) if peers else "none yet"
        purpose = _cell(e.get("scientific_purpose", ""))
        if len(purpose) > 140:
            purpose = purpose[:137].rstrip() + "..."
        entry_link = f"[{e.get('id')}](entries/{Path(e['_file']).name})"
        lines.append(
            f"| {entry_link} | {e.get('type')} | {e.get('origin')} | {purpose} | {_cell(e.get('credentials'))} | "
            f"{(st.get('review') or '?')} | {((st.get('local_verification') or {}).get('result') or '?')} | {peer} | "
            f"{((st.get('hosting') or {}).get('status') or '?')} |"
        )
    lines.append("")
    return "\n".join(lines)


def search(root: Path, terms: list[str]) -> list[dict]:
    terms = [t.lower() for t in terms]
    hits = []
    for e in load(root):
        blob = yaml.safe_dump({k: v for k, v in e.items() if k != "_file"}).lower()
        if all(t in blob for t in terms):
            hits.append(e)
    return hits


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("search")
    s.add_argument("terms", nargs="+")
    sh = sub.add_parser("show")
    sh.add_argument("id")
    sub.add_parser("index")
    args = p.parse_args(argv)

    if args.cmd == "index":
        (REPO / "catalog" / "index.md").write_text(render_index(REPO), encoding="utf-8", newline="\n")
        print("wrote catalog/index.md")
        return 0
    if args.cmd == "show":
        for e in load(REPO):
            if e.get("id") == args.id:
                print(Path(REPO / e["_file"]).read_text(encoding="utf-8"))
                return 0
        print(f"No entry '{args.id}'.", file=sys.stderr)
        return 1
    hits = search(REPO, args.terms)
    if not hits:
        print("No catalog entries match all terms. Try fewer or broader words.")
        return 0
    for e in hits:
        st = e.get("status") or {}
        tools = e.get("tools") or e.get("requires_mcp_tools") or []
        print(f"{e['id']}  [{e['type']}, {e['origin']}, review={st.get('review')}, "
              f"hosting={(st.get('hosting') or {}).get('status')}]")
        print(f"    {' '.join(str(e.get('scientific_purpose', '')).split())[:200]}")
        if tools:
            print(f"    tools: {', '.join(tools)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
